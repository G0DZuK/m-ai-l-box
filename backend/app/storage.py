"""Private object storage: S3-compatible (MinIO locally) or a local directory (tests / lite dev).

Object keys are always generated by the application from UUIDs — never from user-supplied
filenames — so untrusted names can never influence where data is written.
"""
from __future__ import annotations

import os
import re
from collections.abc import Iterator
from functools import lru_cache
from pathlib import Path
from typing import BinaryIO, Protocol

from .config import get_settings

_KEY_RE = re.compile(r"^[a-z0-9][a-z0-9/_.-]{0,199}$")
CHUNK = 64 * 1024


class StorageError(Exception):
    pass


def validate_key(key: str) -> str:
    if not _KEY_RE.match(key) or ".." in key or key.startswith("/") or "//" in key:
        raise StorageError("invalid object key")
    return key


class ObjectStorage(Protocol):
    def put_bytes(self, key: str, data: bytes, content_type: str = "application/octet-stream") -> None: ...
    def put_file(self, key: str, fileobj: BinaryIO, content_type: str = "application/octet-stream") -> None: ...
    def get_bytes(self, key: str, max_bytes: int | None = None) -> bytes: ...
    def iter_chunks(self, key: str) -> Iterator[bytes]: ...
    def copy(self, src: str, dst: str) -> None: ...
    def delete(self, key: str) -> None: ...
    def check(self) -> None: ...


class LocalStorage:
    def __init__(self, root: str):
        self.root = Path(root).resolve()
        self.root.mkdir(parents=True, exist_ok=True)

    def _path(self, key: str) -> Path:
        validate_key(key)
        p = (self.root / key).resolve()
        if self.root not in p.parents:
            raise StorageError("invalid object key")
        return p

    def put_bytes(self, key, data, content_type="application/octet-stream"):
        p = self._path(key)
        p.parent.mkdir(parents=True, exist_ok=True)
        tmp = p.with_suffix(p.suffix + ".part")
        tmp.write_bytes(data)
        os.replace(tmp, p)

    def put_file(self, key, fileobj, content_type="application/octet-stream"):
        p = self._path(key)
        p.parent.mkdir(parents=True, exist_ok=True)
        tmp = p.with_suffix(p.suffix + ".part")
        with open(tmp, "wb") as fh:
            while chunk := fileobj.read(CHUNK):
                fh.write(chunk)
        os.replace(tmp, p)

    def get_bytes(self, key, max_bytes=None):
        p = self._path(key)
        try:
            with open(p, "rb") as fh:
                return fh.read() if max_bytes is None else fh.read(max_bytes)
        except FileNotFoundError as exc:
            raise StorageError("object not found") from exc

    def iter_chunks(self, key):
        p = self._path(key)
        if not p.exists():
            raise StorageError("object not found")

        def gen():
            with open(p, "rb") as fh:
                while chunk := fh.read(CHUNK):
                    yield chunk

        return gen()

    def copy(self, src, dst):
        self.put_bytes(dst, self.get_bytes(src))

    def delete(self, key):
        try:
            self._path(key).unlink()
        except FileNotFoundError:
            pass

    def check(self):
        if not self.root.exists():
            raise StorageError("storage root missing")


class S3Storage:
    def __init__(self):
        import boto3
        from botocore.config import Config

        s = get_settings()
        self.bucket = s.s3_bucket
        self.client = boto3.client(
            "s3",
            endpoint_url=s.s3_endpoint_url or None,
            region_name=s.s3_region,
            aws_access_key_id=s.s3_access_key_id,
            aws_secret_access_key=s.s3_secret_access_key,
            config=Config(signature_version="s3v4", retries={"max_attempts": 5, "mode": "standard"}),
        )
        if s.s3_create_bucket:
            self._ensure_bucket()

    def _ensure_bucket(self):
        from botocore.exceptions import ClientError

        try:
            self.client.head_bucket(Bucket=self.bucket)
        except ClientError:
            self.client.create_bucket(Bucket=self.bucket)
        # Buckets are private by default; make sure no public policy is attached.

    def put_bytes(self, key, data, content_type="application/octet-stream"):
        self.client.put_object(Bucket=self.bucket, Key=validate_key(key), Body=data, ContentType=content_type)

    def put_file(self, key, fileobj, content_type="application/octet-stream"):
        self.client.upload_fileobj(fileobj, self.bucket, validate_key(key), ExtraArgs={"ContentType": content_type})

    def get_bytes(self, key, max_bytes=None):
        from botocore.exceptions import ClientError

        kwargs = {"Bucket": self.bucket, "Key": validate_key(key)}
        if max_bytes is not None:
            kwargs["Range"] = f"bytes=0-{max_bytes - 1}"
        try:
            return self.client.get_object(**kwargs)["Body"].read()
        except ClientError as exc:
            raise StorageError("object not found") from exc

    def iter_chunks(self, key):
        from botocore.exceptions import ClientError

        try:
            body = self.client.get_object(Bucket=self.bucket, Key=validate_key(key))["Body"]
        except ClientError as exc:
            raise StorageError("object not found") from exc
        return body.iter_chunks(CHUNK)

    def copy(self, src, dst):
        self.client.copy_object(
            Bucket=self.bucket, Key=validate_key(dst), CopySource={"Bucket": self.bucket, "Key": validate_key(src)}
        )

    def delete(self, key):
        self.client.delete_object(Bucket=self.bucket, Key=validate_key(key))

    def check(self):
        self.client.head_bucket(Bucket=self.bucket)


@lru_cache
def get_storage() -> ObjectStorage:
    s = get_settings()
    if s.storage_backend == "local":
        return LocalStorage(s.storage_local_path)
    return S3Storage()
